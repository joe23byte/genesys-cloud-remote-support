export const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, de };

export function resolveLang(...candidates: Array<string | null | undefined>): Lang {
  for (const c of candidates) {
    if (!c) continue;
    const l = c.toLowerCase();
    if (l.startsWith('de')) return 'de';
    if (l.startsWith('en')) return 'en';
  }
  return 'en';
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

export const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'en', setLang: () => {} });

export function useT() {
  const { lang } = useContext(I18nContext);
  return (key: MessageKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export const statusKey = (s: SessionStatus): MessageKey => `status.${s}` as MessageKey;
